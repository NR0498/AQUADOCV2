"""Render the model card markdown from the exported model metadata JSON.

    python -m training.model_card    # writes docs/models/water_quality_v1.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from aquadoc_core.wq_model import DEFAULT_MODEL_NAME, MODELS_DIR

PROJECT_ROOT = Path(__file__).resolve().parents[1]

LABELS = {
    "chlorophyll_a": "Chlorophyll-a",
    "tss": "Total suspended solids",
    "cdom_a440": "CDOM absorption at 440 nm",
    "turbidity": "Turbidity",
    "secchi_depth": "Secchi depth (clarity)",
}


def _fmt(metrics: dict, key: str) -> str:
    value = metrics.get(key)
    return "–" if value is None else f"{value}"


def render(metadata: dict) -> str:
    data = metadata["training_data"]
    config = metadata["config"]
    lines = [
        f"# Model card: {metadata['model_version']}",
        "",
        "Generated by `python -m training.model_card` from "
        f"`aquadoc_core/models/{DEFAULT_MODEL_NAME}.json`; do not edit by hand.",
        "",
        "## Purpose",
        "",
        "Estimate optically active water-quality parameters for each water pixel of a Sentinel-2 "
        "Level-2A scene. Outputs are model estimates with calibrated intervals, not measurements. "
        "The model cannot detect non-optical pollutants (heavy metals, bacteria, dissolved nutrients, "
        "pesticides); those require laboratory analysis.",
        "",
        "## Inputs",
        "",
        f"- {metadata['input']}",
        f"- Bands: {', '.join(metadata['bands'])}",
        f"- Feature version `{metadata['feature_version']}`: " + ", ".join(f"`{n}`" for n in metadata["feature_names"]),
        "",
        "## Training data",
        "",
        f"- {data['source']}",
        f"- {data['input_spectra']} spectra; {data['excluded_qc_flagged']} removed by GLORIA QC flags; "
        f"{data['excluded_incomplete_b2_b7']} removed for incomplete B2–B7 coverage; "
        f"**{data['training_spectra']} used** from {data['datasets']} datasets in {data['spatial_groups']} spatial groups.",
        "- Hyperspectral Rrs convolved with ESA Sentinel-2 v4.0 spectral response functions (mean of S2A/S2B/S2C).",
        f"- Training table SHA-256 `{data['table_sha256']}`.",
        "",
        "## Method",
        "",
        f"- Per target: ensemble of {config['n_members']} MLPs {tuple(config['hidden_layers'])}, ReLU, "
        f"L2 = {config['alpha']}, trained on log10(target) with bootstrap resampling.",
        f"- Augmentation: {config['augment_copies']} noisy copies per spectrum, "
        f"{config['multiplicative_noise']:.0%} spectrally flat gain error and "
        f"{config['additive_noise']} sr⁻¹ per-band offset, to approximate satellite radiometric and "
        "atmospheric-correction error.",
        f"- Splits by ~28 km spatial cells: {config['test_fraction']:.0%} of groups held out for testing, "
        f"{config['calibration_fraction']:.0%} of the remaining groups for interval calibration.",
        f"- {config['interval_level']:.0%} intervals from normalized split-conformal prediction on the calibration groups.",
        "- Deployment rule, fixed before training: a target ships only if its test MdSA beats both the "
        "train-median dummy and the published algorithm (when one exists).",
        "",
        "## Results on held-out spatial groups",
        "",
        "MdSA = median symmetric accuracy (lower is better; 100% means a typical factor-of-two error). "
        "SSPB = signed bias.",
        "",
        "| Target | Unit | Deployed | n test | Model MdSA | Model SSPB | R² (log) | With satellite noise | "
        "Dummy MdSA | Published algorithm MdSA | Gradient boosting MdSA | 80% interval coverage | Median interval factor |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for target, spec in metadata["targets"].items():
        ev = spec["evaluation"]
        published = ev.get("published_algorithm")
        published_text = f"{published['mdsa_pct']} ({published['name']})" if published and published.get("n") else "–"
        lines.append(
            f"| {LABELS.get(target, target)} | {spec['unit']} | {'yes' if spec['deployed'] else 'no'} | "
            f"{ev['model']['n']} | {_fmt(ev['model'], 'mdsa_pct')}% | {_fmt(ev['model'], 'sspb_pct')}% | "
            f"{_fmt(ev['model'], 'r2_log10')} | {_fmt(ev['model_with_simulated_satellite_noise'], 'mdsa_pct')}% | "
            f"{_fmt(ev['dummy_train_median'], 'mdsa_pct')}% | {published_text} | "
            f"{_fmt(ev['reference_gradient_boosting'], 'mdsa_pct')}% | {ev['interval_coverage']:.0%} | "
            f"×{ev['median_interval_factor']} |"
        )
    lines += ["", "### By water-body type (model MdSA, groups with ≥20 test samples)", ""]
    types = sorted({t for spec in metadata["targets"].values() for t in spec["evaluation"]["model_by_water_body_type"]})
    lines.append("| Target | " + " | ".join(types) + " |")
    lines.append("| --- | " + " | ".join("---:" for _ in types) + " |")
    for target, spec in metadata["targets"].items():
        by_type = spec["evaluation"]["model_by_water_body_type"]
        cells = [f"{by_type[t]['mdsa_pct']}% (n={by_type[t]['n']})" if t in by_type else "–" for t in types]
        lines.append(f"| {LABELS.get(target, target)} | " + " | ".join(cells) + " |")
    correction = metadata.get("satellite_correction")
    if correction:
        lines += [
            "",
            "## Validation on real Sentinel-2 pixels",
            "",
            f"{correction['matchups']} satellite/in-situ match-ups from {correction['sites']} sites "
            f"(Sentinel-2 L2A within {correction['max_hours_apart']:g} h of a GLORIA sample, cloud-free, homogeneous "
            f"3×3 open-water core; mostly lakes: {correction['by_water_body_type']}). Scores come from a model retrained "
            "**without** these sites, so they are honest out-of-sample satellite errors.",
            "",
            "| Target | n | In-situ Rrs input (upper bound) | Satellite raw | Satellite corrected | Used | "
            "Published algorithm (corrected) | 80% interval coverage (grouped CV) |",
            "| --- | ---: | ---: | ---: | ---: | --- | ---: | ---: |",
        ]
        for target, spec in metadata["targets"].items():
            v = spec.get("satellite_validation") or {}
            if "satellite_raw" not in v:
                continue
            use = spec.get("satellite_input", "raw")
            published = v.get("published_algorithm_on_corrected_satellite", {}).get("mdsa_pct", "–")
            lines.append(
                f"| {LABELS.get(target, target)} | {v['n']} | {v['in_situ_rrs']['mdsa_pct']}% | "
                f"{v['satellite_raw']['mdsa_pct']}% | {v['satellite_corrected']['mdsa_pct']}% | {use} | "
                f"{published}{'%' if published != '–' else ''} | {v[f'interval_coverage_cv_{use}']:.0%} |")
        lines += ["", "Residual reflectance correction (Rrs = intercept + gain·Rrs_L2A + k·Rrs_L2A(B11)):", "",
                  "| Band | Intercept (sr⁻¹) | Gain | B11 coefficient | Raw median offset (sr⁻¹) | After correction (CV) |",
                  "| --- | ---: | ---: | ---: | ---: | ---: |"]
        for band, c in correction["coefficients"].items():
            lines.append(f"| {band} | {c['intercept']:.5f} | {c['gain']:.3f} | {c['swir_b11']:.3f} | "
                         f"{correction['radiometry_raw'][band]['median_difference_sr']} | "
                         f"{correction['radiometry_corrected_cv'][band]['median_difference_sr']} |")
        lines += ["", "Each target uses the input that validated better; intervals are recalibrated on satellite "
                      "residuals for that input. Confidence shown in results: *high* needs satellite MdSA ≤ 40%, "
                      "*low* is forced above 100%."]
    lines += ["", "### Training range (1st–99th percentile)", ""]
    for target, spec in metadata["targets"].items():
        low, high = spec["target_range_p01_p99"]
        lines.append(f"- {LABELS.get(target, target)}: {low:.3g} – {high:.3g} {spec['unit']}")
    lines += [
        "",
        "## Known limitations",
        "",
        "- **Domain gap.** Training spectra are in-situ radiometer measurements; the deployed model receives "
        "satellite reflectance after Sen2Cor atmospheric correction, which was designed for land. The held-out "
        "test scores are therefore an upper bound; the satellite validation section measures the real gap, which "
        "the residual correction narrows but does not close (worst for CDOM, which relies on the blue bands).",
        "- **Match-up coverage.** Satellite validation is dominated by lakes; rivers and estuaries are barely "
        "represented, so their satellite accuracy is unknown.",
        "- **Spatial representativeness.** GLORIA over-represents some regions and water types; "
        "performance elsewhere is not guaranteed.",
        "- **Adjacency and bottom effects.** Near-shore pixels, shallow clear water and floating vegetation violate the "
        "model's optically-deep open-water assumption. The pipeline masks shorelines, but cannot detect every case.",
        "- **Out-of-domain inputs** (features outside the training 1st–99th percentile) are flagged per pixel.",
        "- **Interval coverage** is measured on held-out groups; values below the nominal level mean intervals are "
        "too narrow for new regions.",
        "- Turbidity training labels are NTU from mixed instruments; Sentinel-2-based turbidity is often reported in FNU.",
        "",
        "## Environment",
        "",
        "```json",
        json.dumps(metadata["environment"], indent=2),
        "```",
        "",
        f"Trained {metadata['trained_at']}.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", type=Path, default=MODELS_DIR / f"{DEFAULT_MODEL_NAME}.json")
    parser.add_argument("--output", type=Path, default=PROJECT_ROOT / "docs" / "models" / f"{DEFAULT_MODEL_NAME}.md")
    args = parser.parse_args(argv)
    metadata = json.loads(args.model.read_text(encoding="utf-8"))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(metadata), encoding="utf-8")
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
